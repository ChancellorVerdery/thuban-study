import Foundation
import Observation
import ThubanCore
import UniformTypeIdentifiers
import os

/// Per-class UI state: section, the study queue and current instance, inputs/verdicts, graph state, toggles, the
/// tutor transcript and the import queue. Grading, tutoring and the import pipeline are added by the screens in
/// extensions (`ClassSession+Grading.swift`, `ClassSession+Tutor.swift`, `ClassSession+Import.swift`).
@MainActor
@Observable
final class ClassSession {
    static let logger = Logger(subsystem: "com.thuban.study", category: "session")

    enum Section: String, CaseIterable, Identifiable, Sendable {
        case study, questionBank, importDocs

        var id: String { rawValue }
        var label: String {
            switch self {
            case .study: return "Study"
            case .questionBank: return "Question Bank"
            case .importDocs: return "Import"
            }
        }
    }

    let classId: ClassID
    /// The owning model (services: store, engine, credentials, policy).
    unowned let app: AppModel

    var studyClass: StudyClass? { app.classes.first { $0.id == classId } }
    var store: Store { app.store }
    var engine: MathEngine { app.engine }

    // MARK: Section

    var section: Section = .study

    // MARK: Study state

    /// The study queue: needsReview → new → learning → mastered (stable within a group).
    private(set) var questions: [Question] = []
    /// Mastery per question (missing ⇒ `.new`).
    private(set) var progress: [QuestionID: QuestionProgress] = [:]
    private(set) var isLoadingQuestions = false
    private(set) var currentIndex: Int = 0
    var currentQuestion: Question? {
        questions.indices.contains(currentIndex) ? questions[currentIndex] : nil
    }
    var currentInstance: QuestionInstance?
    /// Set while an instance is being generated by the engine.
    private(set) var isInstantiating = false
    /// Bumped by every `instantiate`; a call whose generation is stale by the time the engine returns discards its
    /// result, so rapid Next/Previous cannot leave `currentInstance` belonging to a different question.
    @ObservationIgnored private var instantiateGeneration = 0
    /// The unstructured instantiate started by `next()`/`previous()`, replaced (and cancelled) by the next one.
    @ObservationIgnored private var instantiateTask: Task<Void, Never>?
    /// partId → LaTeX / text typed by the student for the current instance.
    var inputs: [String: String] = [:]
    /// partId → verdict for the current instance (cleared on regenerate / next).
    var verdicts: [String: Verdict] = [:]
    /// Latest recoverable error to surface in the UI (engine, store).
    var lastError: String?

    var questionCount: Int { questions.count }
    /// 1-based position for "Question n of N".
    var questionNumber: Int { questions.isEmpty ? 0 : currentIndex + 1 }

    // MARK: Tool toggles and graph

    var showGraph = false
    var showCalculator = false
    var showKeyboard = false
    var graphMode: GraphMode = .twoD
    /// Every expression the app knows about, in both modes (each row carries its `mode`; Desmos keeps one list per mode).
    var graphExpressions: [GraphExpression] = []
    /// The rows on the calculator the student is looking at right now.
    var visibleGraphExpressions: [GraphExpression] { graphExpressions.filter { $0.mode == graphMode } }
    /// The last viewport the tutor asked for (2D); re-applied when the graph page comes up after the request.
    var graphViewport: GraphViewport?
    /// When the tutor last changed the graph (drives the "Tutor is editing" chip for 5 s).
    var tutorEditedAt: Date?
    var tutorEditedRecently: Bool {
        guard let tutorEditedAt else { return false }
        return Date().timeIntervalSince(tutorEditedAt) < 5
    }

    // MARK: Tutor

    var transcript: [TutorMessage] = []
    var isTutorStreaming = false

    // MARK: Import

    var importQueue: [ImportedDocument] = []

    // MARK: Init

    init(classId: ClassID, app: AppModel) {
        self.classId = classId
        self.app = app
    }

    // MARK: Questions

    /// Fetches the class's questions and progress, orders the queue and instantiates the first question
    /// (keeping the current one when it is still in the bank).
    func loadQuestions() async {
        isLoadingQuestions = true
        defer { isLoadingQuestions = false }
        do {
            let all = try await store.questions(in: classId, filter: nil)
            let rows = try await store.progress(in: classId)
            progress = Dictionary(rows.map { ($0.questionId, $0) }, uniquingKeysWith: { _, last in last })
            let previousId = currentQuestion?.id
            questions = Self.ordered(all, progress: progress)
            if let previousId, let index = questions.firstIndex(where: { $0.id == previousId }) {
                currentIndex = index
            } else {
                currentIndex = 0
                if let first = questions.first {
                    await instantiate(first, seed: nil)
                } else {
                    currentInstance = nil
                    inputs = [:]
                    verdicts = [:]
                }
            }
        } catch {
            lastError = error.localizedDescription
            Self.logger.error("loadQuestions failed: \(error.localizedDescription, privacy: .public)")
        }
    }

    /// Refreshes `progress` only (after an attempt is recorded).
    func reloadProgress() async {
        guard let rows = try? await store.progress(in: classId) else { return }
        progress = Dictionary(rows.map { ($0.questionId, $0) }, uniquingKeysWith: { _, last in last })
    }

    func status(of question: Question) -> ProgressStatus {
        progress[question.id]?.status ?? .new
    }

    /// Fraction of the bank mastered, for the progress bar.
    var masteredFraction: Double {
        guard !questions.isEmpty else { return 0 }
        let mastered = questions.filter { status(of: $0) == .mastered }.count
        return Double(mastered) / Double(questions.count)
    }

    /// Jumps to a question (from the bank) and instantiates it.
    func select(question: Question) async {
        if let index = questions.firstIndex(where: { $0.id == question.id }) {
            currentIndex = index
        } else {
            questions.append(question)
            currentIndex = questions.count - 1
        }
        section = .study
        await instantiate(question, seed: nil)
    }

    /// "Regenerate numbers" applies to math templates only, and not while an instance is being built.
    var canRegenerate: Bool {
        currentQuestion?.kind == .mathTemplate && !isInstantiating
    }

    /// Fresh numbers for the current template question (static questions just reset the form).
    func regenerate() async {
        guard let question = currentQuestion else { return }
        await instantiate(question, seed: nil)
    }

    /// Advances to the next question in the queue (wrapping) and instantiates it.
    func next() {
        guard !questions.isEmpty else { return }
        currentIndex = (currentIndex + 1) % questions.count
        instantiateCurrentInBackground()
    }

    func previous() {
        guard !questions.isEmpty else { return }
        currentIndex = (currentIndex - 1 + questions.count) % questions.count
        instantiateCurrentInBackground()
    }

    /// One in-flight background instantiate at a time: a newer Next/Previous replaces the older one.
    private func instantiateCurrentInBackground() {
        guard let question = currentQuestion else { return }
        instantiateTask?.cancel()
        instantiateTask = Task { [weak self] in await self?.instantiate(question, seed: nil) }
    }

    /// Builds the instance shown to the student: templates through the engine (deterministic for a seed),
    /// everything else verbatim. Clears inputs and verdicts. A call that is overtaken by a newer one (or whose
    /// question is no longer the current one) discards its result.
    func instantiate(_ question: Question, seed: String?) async {
        instantiateGeneration &+= 1
        let generation = instantiateGeneration
        isInstantiating = true
        defer { if generation == instantiateGeneration { isInstantiating = false } }
        inputs = [:]
        verdicts = [:]
        if let template = question.template, question.kind == .mathTemplate {
            do {
                let instance = try await engine.instantiate(template, seed: seed, questionId: question.id)
                guard generation == instantiateGeneration, currentQuestion?.id == question.id else { return }
                currentInstance = instance
                return
            } catch {
                guard generation == instantiateGeneration, currentQuestion?.id == question.id else { return }
                lastError = error.localizedDescription
                Self.logger.error("instantiate failed for \(question.id.raw, privacy: .public): \(error.localizedDescription, privacy: .public)")
                // Fall back to the static parts so the student still sees something.
            }
        }
        guard generation == instantiateGeneration, currentQuestion?.id == question.id else { return }
        currentInstance = QuestionInstance(static: question, seed: seed ?? Self.randomSeed())
    }

    /// 8 hex chars.
    static func randomSeed() -> String {
        String(format: "%08x", UInt32.random(in: UInt32.min...UInt32.max))
    }

    /// needsReview → new → learning → mastered; stable by `createdAt` inside each group.
    static func ordered(_ questions: [Question], progress: [QuestionID: QuestionProgress]) -> [Question] {
        func rank(_ status: ProgressStatus) -> Int {
            switch status {
            case .needsReview: return 0
            case .new: return 1
            case .learning: return 2
            case .mastered: return 3
            }
        }
        return questions
            .enumerated()
            .sorted { lhs, rhs in
                let l = rank(progress[lhs.element.id]?.status ?? .new)
                let r = rank(progress[rhs.element.id]?.status ?? .new)
                if l != r { return l < r }
                if lhs.element.createdAt != rhs.element.createdAt { return lhs.element.createdAt < rhs.element.createdAt }
                return lhs.offset < rhs.offset
            }
            .map(\.element)
    }

    // MARK: Graph helpers

    /// Adds or replaces an expression by id and marks tutor edits.
    func upsertGraphExpression(_ expression: GraphExpression) {
        if let index = graphExpressions.firstIndex(where: { $0.id == expression.id }) {
            graphExpressions[index] = expression
        } else {
            graphExpressions.append(expression)
        }
        if expression.fromTutor { tutorEditedAt = Date() }
    }

    func removeGraphExpression(id: String, byTutor: Bool = false) {
        graphExpressions.removeAll { $0.id == id }
        if byTutor { tutorEditedAt = Date() }
    }

    /// Removes the rows of the mode on screen (what Desmos' `clear` does); the other mode's rows survive.
    func clearGraph(byTutor: Bool = false) {
        let mode = graphMode
        graphExpressions.removeAll { $0.mode == mode }
        if byTutor { tutorEditedAt = Date() }
    }

    // MARK: Documents

    /// Loads the class's imported documents into `importQueue`. A document left mid-import by a quit or a crash
    /// (a non-terminal status that no running pipeline owns) goes back to the queue so it can run again.
    func loadDocuments() async {
        do {
            var documents = try await store.documents(in: classId)
            let pipeline = importPipeline
            let live = pipeline.isRunning ? pipeline.batchIds : []
            for index in documents.indices {
                let document = documents[index]
                guard document.status != .queued, !document.status.isTerminal, !live.contains(document.id) else { continue }
                Self.logger.notice("Resetting interrupted import of \(document.filename, privacy: .public) (was \(document.status.rawValue, privacy: .public))")
                try await store.update(status: .queued, detail: "Interrupted", model: nil, for: document.id)
                documents[index].status = .queued
                documents[index].statusDetail = "Interrupted"
                documents[index].modelUsed = nil
            }
            importQueue = documents
        } catch {
            lastError = error.localizedDescription
        }
    }

    /// Puts a failed document back in the queue; its stored copy is still on disk, so the next run retries it.
    func retryDocument(_ id: DocumentID) async {
        guard var document = importQueue.first(where: { $0.id == id }), document.status == .failed else { return }
        do {
            try await store.update(status: .queued, detail: "Retry", model: nil, for: id)
            document.status = .queued
            document.statusDetail = "Retry"
            document.modelUsed = nil
            updateDocument(document)
        } catch {
            lastError = error.localizedDescription
        }
    }

    /// Copies dropped files under `AppPaths.documents/<classId>/` and records them as queued documents.
    /// The import pipeline (screens phase) picks queued documents up from `importQueue`.
    @discardableResult
    func enqueue(urls: [URL]) async -> [ImportedDocument] {
        var added: [ImportedDocument] = []
        var seen: Set<String> = []
        var duplicates: [String] = []
        for url in urls {
            // The same file twice in one drop counts once.
            guard seen.insert(url.standardizedFileURL.path).inserted else { continue }
            let filename = url.lastPathComponent
            let id = DocumentID.new()
            let relative = "\(classId.raw)/\(id.raw)-\(filename)"
            let destination = AppPaths.documentURL(relative)
            do {
                let accessing = url.startAccessingSecurityScopedResource()
                defer { if accessing { url.stopAccessingSecurityScopedResource() } }
                // A file already in the class (same name and size) is not imported a second time.
                let sourceSize = (try? FileManager.default.attributesOfItem(atPath: url.path)[.size] as? Int) ?? -1
                if importQueue.contains(where: { $0.filename == filename && $0.byteCount == sourceSize }) {
                    duplicates.append(filename)
                    continue
                }
                // The copy runs off the main actor: a large PDF or a network volume must not freeze the window.
                let size = try await Self.copyFile(from: url, to: destination)
                let document = ImportedDocument(
                    id: id,
                    classId: classId,
                    filename: filename,
                    kind: DocumentParserRegistry.kind(for: url),
                    storedPath: relative,
                    byteCount: size
                )
                try await store.insert(document)
                importQueue.append(document)
                added.append(document)
            } catch {
                lastError = "Could not add \(filename): \(error.localizedDescription)"
                Self.logger.error("enqueue failed for \(filename, privacy: .public): \(error.localizedDescription, privacy: .public)")
            }
        }
        if !duplicates.isEmpty {
            let names = duplicates.joined(separator: ", ")
            lastError = duplicates.count == 1
                ? "\(names) is already in this class; remove it first to import it again."
                : "Already in this class, skipped: \(names). Remove a file first to import it again."
        }
        return added
    }

    /// Copies `source` to `destination` (creating its folder) on a background thread and returns the copied size.
    private static func copyFile(from source: URL, to destination: URL) async throws -> Int {
        try await Task.detached(priority: .userInitiated) {
            let fm = FileManager.default
            try fm.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
            try fm.copyItem(at: source, to: destination)
            return (try? fm.attributesOfItem(atPath: destination.path)[.size] as? Int) ?? 0
        }.value
    }

    /// Replaces a document row in `importQueue` (status updates from the pipeline).
    func updateDocument(_ document: ImportedDocument) {
        if let index = importQueue.firstIndex(where: { $0.id == document.id }) {
            importQueue[index] = document
        } else {
            importQueue.append(document)
        }
    }

    func removeDocument(_ id: DocumentID, deleteFiles: Bool = true) async {
        do {
            try await store.delete(id, deleteFiles: deleteFiles)
            importQueue.removeAll { $0.id == id }
        } catch {
            lastError = error.localizedDescription
        }
    }
}
